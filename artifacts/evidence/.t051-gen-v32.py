def apply(text: str, edits: list[tuple[str, str, str]], label: str) -> str:
    for name, old, new in edits:
        n = text.count(old)
        if n != 1:
            print(f"FAIL [{label}] {name}: 命中 {n} 次（应为 1），中止", file=sys.stderr)
            raise SystemExit(2)
        text = text.replace(old, new)
        print(f"OK   [{label}] {name}")
    return text


def main() -> int:
    if not SRC.is_file():
        print(f"FAIL 基线不存在：{SRC}", file=sys.stderr)
        return 2
    src_text = SRC.read_text(encoding="utf-8")
    out = apply(src_text, HEADER_EDITS, "header")
    out = apply(out, REWRITES, "ia")
    DST.write_text(out, encoding="utf-8", newline="\n")
    print(f"WROTE {DST}")
    print(f"lines src={len(src_text.splitlines())} dst={len(out.splitlines())}")
    return 0


